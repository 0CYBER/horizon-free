#!/usr/bin/env python3
"""Generate sync_registries.rs: synchronised registries and entries that older
vanilla releases lack compared with 26.3. Read-only on all inputs."""
import io
import os
import re
import sys
import zipfile

DATA_RS = os.path.join(os.path.dirname(__file__), "..", "crates", "horizon-client", "src", "lan", "data.rs")
OUT_RS = os.path.join(os.path.dirname(__file__), "..", "crates", "horizon-protocol", "src", "adapter", "client_session", "sync_registries.rs")
REFERENCE = ("26.3", "/home/leo/horizon-dev/.local/datagen/versions/26.3/server-26.3.jar")
RELEASES = [
    ("1.20.2", "~/code/horizon-parity/versions/1.20.2/jars/server.jar"),
    ("1.20.4", "~/code/horizon-parity/versions/1.20.4/jars/server.jar"),
    ("1.20.6", "~/code/horizon-parity/versions/1.20.6/jars/server.jar"),
    ("1.21.1", "~/code/horizon-parity/versions/1.21.1/jars/server.jar"),
    ("1.21.3", "~/code/horizon-parity/versions/1.21.3/jars/server.jar"),
    ("1.21.4", "~/code/horizon-parity/versions/1.21.4/jars/server.jar"),
    ("1.21.5", "~/code/horizon-parity/versions/1.21.5/jars/server.jar"),
    ("1.21.6", "~/code/horizon-parity/versions/1.21.6/jars/server.jar"),
    ("1.21.8", "~/code/horizon-parity/versions/1.21.8/jars/server.jar"),
    ("1.21.9", "~/code/horizon-parity/versions/1.21.9/jars/server.jar"),
    ("1.21.10", "~/code/horizon-parity/versions/1.21.10/jars/server.jar"),
    ("1.21.11", "~/code/horizon-parity/versions/1.21.11/jars/server.jar"),
    ("26.1.2", "~/code/horizon-parity/versions/26.1.2/jars/server.jar"),
    ("26.2", "/home/leo/CoreSMP/servers/rec_world/versions/26.2/paper-26.2.jar"),
]
BUNDLED = re.compile(r"META-INF/versions/[^/]+/server-[^/]+\.jar")


def read_synchronized(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = re.search(r"pub const SYNCHRONIZED: &\[&str\] = &\[(.*?)\];", text, re.S)
    if not m:
        sys.exit("SYNCHRONIZED list not found in data.rs")
    keys = re.findall(r'"(minecraft:[^"]+)"', m.group(1))
    if not keys:
        sys.exit("SYNCHRONIZED list is empty")
    return keys


def open_server_zip(path):
    """Return a ZipFile holding the real server contents (unwrap bundler jars)."""
    zf = zipfile.ZipFile(os.path.expanduser(path))
    nested = [n for n in zf.namelist() if BUNDLED.fullmatch(n)]
    if nested:
        if len(nested) != 1:
            sys.exit(f"{path}: expected one nested server jar, got {nested}")
        zf = zipfile.ZipFile(io.BytesIO(zf.read(nested[0])))
    return zf


def registry_entries(zf, key):
    """Entry names ('minecraft:<stem>') of the direct *.json children of the registry dir."""
    directory = "data/minecraft/" + key[len("minecraft:"):] + "/"
    entries = set()
    for name in zf.namelist():
        if not name.startswith(directory):
            continue
        rest = name[len(directory):]
        if "/" in rest or not rest.endswith(".json"):
            continue
        entries.add("minecraft:" + rest[:-len(".json")])
    return entries


def snapshot(path, keys):
    zf = open_server_zip(path)
    return {key: registry_entries(zf, key) for key in keys}


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def module_name(release):
    return "v" + release.replace(".", "_")


def main():
    keys = read_synchronized(DATA_RS)
    ref_name, ref_path = REFERENCE
    ref = snapshot(ref_path, keys)
    ref_keys = {k for k in keys if ref[k]}

    modules = []
    for release, path in RELEASES:
        snap = snapshot(path, keys)
        have = {k for k in keys if snap[k]}
        absent = sorted(ref_keys - have)
        lacking = []
        for key in keys:
            if key not in ref_keys or key not in have:
                continue
            missing = sorted(ref[key] - snap[key])
            if missing:
                lacking.append((key, missing))
        n_entries = sum(len(m) for _, m in lacking)
        modules.append((release, absent, lacking))
        print(f"{release}: absent={len(absent)} ({', '.join(k[len('minecraft:'):] for k in absent) or '-'}); "
              f"lacking entries in {len(lacking)} registries, {n_entries} entries")

    out = [
        "// Generated by generate_sync_registry_adapter.py from the vanilla jars. Do not edit by hand.",
        f"// Reference: {ref_name}. Keys: SYNCHRONIZED in horizon-client lan/data.rs.",
        "// ABSENT: synchronised registry keys the release lacks (present in the reference).",
        "// LACKING: (registry key, sorted entry names the release lacks) for shared registries.",
        "",
    ]
    for release, absent, lacking in modules:
        out.append(f"pub mod {module_name(release)} {{")
        out.append("    pub const ABSENT: &[&str] = &[")
        for key in absent:
            out.append(f"        {rust_str(key)},")
        out.append("    ];")
        out.append("    pub const LACKING: &[(&str, &[&str])] = &[")
        for key, missing in lacking:
            out.append(f"        ({rust_str(key)}, &[")
            for name in missing:
                out.append(f"            {rust_str(name)},")
            out.append("        ]),")
        out.append("    ];")
        out.append("}")
        out.append("")

    os.makedirs(os.path.dirname(OUT_RS), exist_ok=True)
    with open(OUT_RS, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT_RS}")


if __name__ == "__main__":
    main()
